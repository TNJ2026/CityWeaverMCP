    public sealed partial class GameQueryService
    {
        private static McpTrafficSignalProgramSystem SignalPrograms(World world) =>
            world.GetOrCreateSystemManaged<McpTrafficSignalProgramSystem>();

        private void ResetTrafficSignalPrograms()
        {
            var world = World.DefaultGameObjectInjectionWorld;
            if (world != null && world.IsCreated)
                world.GetExistingSystemManaged<McpTrafficSignalProgramSystem>()?.ClearAll();
        }

        private JObject InspectIntersectionControls(JObject args, World world)
        {
            var em = world.EntityManager;
            if (!(args["node_ids"] is JArray ids) || ids.Count < 1 || ids.Count > 64)
                throw new QueryException("INVALID_ARGUMENT", "node_ids must contain 1..64 intersection node IDs.");
            var rows = new JArray();
            foreach (var token in ids)
            {
                var node = ParseEntity((string)token, em);
                if (!em.HasComponent<Node>(node) || em.HasComponent<Deleted>(node) || em.HasComponent<Temp>(node))
                    throw new QueryException("INTERSECTION_NOT_FOUND", "Every node_id must identify a permanent road node.");
                var row = new JObject { ["node_id"] = EntityId(node) };
                if (em.HasComponent<TrafficLights>(node))
                {
                    var lights = em.GetComponentData<TrafficLights>(node);
                    row["traffic_lights"] = new JObject {
                        ["enabled"] = true, ["state"] = lights.m_State.ToString(),
                        ["signal_group_count"] = lights.m_SignalGroupCount,
                        ["current_signal_group"] = lights.m_CurrentSignalGroup,
                        ["next_signal_group"] = lights.m_NextSignalGroup,
                        ["timer"] = lights.m_Timer
                    };
                }
                else row["traffic_lights"] = new JObject { ["enabled"] = false };

                var signs = new JArray();
                var signOwners = new List<Entity> { node };
                if (em.HasBuffer<ConnectedEdge>(node))
                {
                    var connected = em.GetBuffer<ConnectedEdge>(node, true);
                    for (int i = 0; i < connected.Length; i++) signOwners.Add(connected[i].m_Edge);
                }
                var seenSigns = new HashSet<Entity>();
                var prefabs = world.GetExistingSystemManaged<PrefabSystem>();
                foreach (var owner in signOwners)
                {
                    if (!em.Exists(owner) || !em.HasBuffer<Game.Objects.SubObject>(owner)) continue;
                    var objects = em.GetBuffer<Game.Objects.SubObject>(owner, true);
                    for (int i = 0; i < objects.Length; i++)
                    {
                        var sign = objects[i].m_SubObject;
                        if (!seenSigns.Add(sign) || !em.Exists(sign) || !em.HasComponent<PrefabRef>(sign)) continue;
                        var prefab = em.GetComponentData<PrefabRef>(sign).m_Prefab;
                        if (!em.HasComponent<TrafficSignData>(prefab)) continue;
                        var data = em.GetComponentData<TrafficSignData>(prefab);
                        prefabs.TryGetPrefab<PrefabBase>(prefab, out var prefabBase);
                        var types = new JArray();
                        foreach (TrafficSignType type in Enum.GetValues(typeof(TrafficSignType)))
                            if (type != TrafficSignType.None && type != TrafficSignType.Count &&
                                (data.m_TypeMask & TrafficSignData.GetTypeMask(type)) != 0) types.Add(type.ToString());
                        signs.Add(new JObject { ["object_id"] = EntityId(sign), ["owner_id"] = EntityId(owner), ["prefab"] = prefabBase?.name,
                            ["supported_sign_types"] = types, ["speed_limit_kph"] = data.m_SpeedLimit });
                    }
                }
                row["traffic_sign_objects"] = signs;
                if (SignalPrograms(world).TryGet(node, out var program)) row["fixed_program"] = SignalProgramJson(program);
                else row["fixed_program"] = null;
                rows.Add(row);
            }
            return new JObject { ["items"] = rows, ["program_scope"] = "current loaded-city session",
                ["sign_note"] = "Traffic signs are generated by native road rules; use intersection rules, road policies and intersection control to change them." };
        }

        private JObject SetTrafficSignalProgram(JObject args, World world)
        {
            if (world.GetExistingSystemManaged<SimulationSystem>().selectedSpeed != 0)
                throw new QueryException("CITY_MUST_BE_PAUSED", "Pause the city before changing a traffic-signal program.");
            var em = world.EntityManager;
            var node = ParseEntity((string)args["node_id"], em);
            if (!em.HasComponent<Node>(node) || !em.HasComponent<TrafficLights>(node) || em.HasComponent<Deleted>(node) || em.HasComponent<Temp>(node))
                throw new QueryException("TRAFFIC_LIGHT_NOT_FOUND", "node_id must identify a permanent node with active traffic lights.");
            var lights = em.GetComponentData<TrafficLights>(node);
            if ((lights.m_Flags & TrafficLightFlags.MoveableBridge) != 0)
                throw new QueryException("UNSUPPORTED_TRAFFIC_LIGHT", "Moveable-bridge signals cannot use a custom fixed program.");
            if (!(args["phases"] is JArray phases) || phases.Count < 1 || phases.Count > 16)
                throw new QueryException("INVALID_ARGUMENT", "phases must contain 1..16 signal-group phases.");
            var offset = (int?)args["offset_steps"] ?? 0;
            if (offset < 0 || offset > 65535)
                throw new QueryException("INVALID_ARGUMENT", "offset_steps must be 0..65535.");
            var plan = new TrafficSignalProgramPlan { Node = node, OffsetSteps = (ushort)offset };
            var seen = new HashSet<byte>();
            foreach (var token in phases)
            {
                if (!(token is JObject phase)) throw new QueryException("INVALID_ARGUMENT", "Each phase must be an object.");
                var group = (int?)phase["signal_group"] ?? 0;
                var duration = (int?)phase["duration_steps"] ?? 0;
                if (group < 1 || group > lights.m_SignalGroupCount)
                    throw new QueryException("INVALID_SIGNAL_GROUP", "signal_group must be between 1 and the node's signal_group_count.");
                if (duration < 1 || duration > 255)
                    throw new QueryException("INVALID_ARGUMENT", "duration_steps must be 1..255.");
                if (!seen.Add((byte)group)) throw new QueryException("DUPLICATE_SIGNAL_GROUP", "Each signal_group may appear only once.");
                plan.Phases.Add(new TrafficSignalPhasePlan { SignalGroup = (byte)group, DurationSteps = (ushort)duration });
            }
            SignalPrograms(world).Set(plan);
            return SignalProgramJson(plan);
        }

        private JObject ClearTrafficSignalProgram(JObject args, World world)
        {
            if (world.GetExistingSystemManaged<SimulationSystem>().selectedSpeed != 0)
                throw new QueryException("CITY_MUST_BE_PAUSED", "Pause the city before clearing a traffic-signal program.");
            var node = ParseEntity((string)args["node_id"], world.EntityManager);
            var removed = SignalPrograms(world).Remove(node);
            return new JObject { ["node_id"] = EntityId(node), ["removed"] = removed,
                ["native_adaptive_control_restored"] = true };
        }

        private JObject SignalProgramJson(TrafficSignalProgramPlan plan) => new JObject {
            ["node_id"] = EntityId(plan.Node), ["offset_steps"] = plan.OffsetSteps,
            ["phases"] = new JArray(plan.Phases.Select(p => new JObject {
                ["signal_group"] = p.SignalGroup, ["duration_steps"] = p.DurationSteps })),
            ["step_definition"] = "16 simulation frames", ["safety_transition_steps"] = 4,
            ["scope"] = "current loaded-city session"
        };
    }
}
